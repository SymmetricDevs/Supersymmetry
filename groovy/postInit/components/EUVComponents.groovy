/// LTE (Low Temperature Expansion) Substrate: Tianium Doped Silica Glass
// This pick is based on [1]

// 1 Titanium Tetrachloride + 4 Isopropanol + 4 Ammonia ==[Benzene]==> 1 Titanium Tetraisopropoxide (benene) + 4 Ammonium Chloride [LCR]
// Based on [4]
LCR.recipeBuilder()
    .fluidInputs(fluid('titanium_tetrachloride') * 1000)
    .fluidInputs(fluid('isopropyl_alcohol') * 4000)
    .fluidInputs(fluid('ammonia') * 4000)
    .fluidInputs(fluid('benzene') * 1000)
    .outputs(ore('dustAmmoniumChloride').first() * 24)
    .fluidOutputs(fluid('titanium_tetraisopropoxide_solution') * 1000)
    .EUt(Globals.voltAmps[3])
    .duration(200)
    .buildAndRegister();

DT.recipeBuilder()
    .fluidInputs(fluid('titanium_tetraisopropoxide_solution') * 1000)
    .fluidOutputs(fluid('titanium_tetraisopropoxide') * 1000)
    .fluidOutputs(fluid('benzene') * 1000)
    .EUt(Globals.voltAmps[3])
    .duration(200)
    .buildAndRegister();


