// 1:15 Titanium Tetraisopropoxide : TEOS dissolved in ethanol
// Based on [2, 3]
MIXER.recipeBuilder()
    .fluidInputs(fluid('titanium_tetraisopropoxide') * 125)
    .fluidInputs(fluid('tetraethoxysilane') * 1875)
    .fluidInputs(fluid('ethanol') * 1000)
    .fluidOutputs(fluid('titanium_silicon_alkoxide_ethanol_solution') * 3000)
    .EUt(Globals.voltAmps[3])
    .duration(200)
    .buildAndRegister();

// Hydrolyzation catalyst is not accurate to literature; adjusted for gameplay
// Based on [2, 3]
POLYMERIZATION.recipeBuilder()
    .fluidInputs(fluid('titanium_silicon_alkoxide_ethanol_solution') * 3000)
    .fluidInputs(fluid('distilled_water') * 1000)
    .fluidInputs(fluid('acetic_acid') * 500)
    .outputs(ore('dustTitaniumDopedSilicaGlass').first() * 3) // gel
    .fluidOutputs(fluid('wastewater') * 3000)
    .EUt(Globals.voltAmps[3])
    .duration(200)
    .buildAndRegister();

// Smelt recipe is autogenerated
// Based on [2, 3]
EBF.recipeBuilder()
